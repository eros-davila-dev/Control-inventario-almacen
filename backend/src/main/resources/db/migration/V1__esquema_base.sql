-- El saldo nunca es negativo ni se reserva mas de lo que existe.
alter table sgai.stock add constraint ck_stock_cantidad_no_negativa check (cantidad >= 0);
alter table sgai.stock add constraint ck_stock_reserva_no_negativa check (cantidad_reservada >= 0);
alter table sgai.stock add constraint ck_stock_reserva_menor check (cantidad_reservada <= cantidad);

-- Toda linea de movimiento mueve una cantidad positiva: el signo lo da el tipo.
alter table sgai.movimiento_linea add constraint ck_mov_linea_cantidad_positiva check (cantidad > 0);
alter table sgai.movimiento_linea add constraint ck_mov_linea_costo_no_negativo check (costo_unitario >= 0);

-- Parametros de reposicion coherentes.
alter table sgai.producto add constraint ck_producto_parametros
    check (stock_minimo <= punto_reorden and punto_reorden <= stock_maximo);
alter table sgai.producto add constraint ck_producto_vida_util check (vida_util_minima_dias >= 0);
alter table sgai.producto add constraint ck_producto_cobertura check (dias_cobertura > 0);

-- Conversion de unidades siempre positiva.
alter table sgai.unidad_medida add constraint ck_um_factor_positivo check (factor_a_base > 0);

-- RUC peruano de 11 digitos.
alter table sgai.proveedor add constraint ck_proveedor_ruc check (ruc ~ '^[0-9]{11}$');

-- Coherencia de fechas del lote.
alter table sgai.lote add constraint ck_lote_fechas
    check (fecha_fabricacion is null or fecha_vencimiento is null
           or fecha_vencimiento > fecha_fabricacion);

-- No se recibe mas de lo pedido ni se despacha mas de lo solicitado.
alter table sgai.orden_compra_linea add constraint ck_oc_linea_recibida
    check (cantidad_recibida <= cantidad);
alter table sgai.requisicion_linea add constraint ck_req_linea_atendida
    check (cantidad_atendida <= cantidad_solicitada);
alter table sgai.transferencia_linea add constraint ck_transf_linea_recibida
    check (cantidad_recibida is null or cantidad_recibida <= cantidad_enviada);

-- Totales de la orden de compra no negativos.
alter table sgai.orden_compra add constraint ck_oc_totales
    check (subtotal >= 0 and igv >= 0 and total >= 0);

-- =====================================================================
-- Unicidad del saldo por producto - almacen - lote - ubicacion.
-- Se usa un indice sobre expresion porque lote_id y ubicacion_id son
-- opcionales y en SQL dos NULL no son iguales.
-- =====================================================================
create unique index uq_stock_celda on sgai.stock
    (producto_id, almacen_id, coalesce(lote_id, 0), coalesce(ubicacion_id, 0));

-- Una sola alerta abierta por tipo + producto + almacen + lote.
create unique index uq_alerta_abierta on sgai.alerta
    (tipo_alerta, coalesce(producto_id, 0), coalesce(almacen_id, 0), coalesce(lote_id, 0))
    where estado <> 'RESUELTA';

